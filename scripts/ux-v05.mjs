// V05 使用獨立瀏覽器資料驗證；先 verify 並啟動本機 preview。
import assert from 'node:assert/strict'
import { mkdirSync, readdirSync } from 'node:fs'
import { homedir } from 'node:os'
import { chromium } from 'playwright-core'
const cache = `${homedir()}/.cache/ms-playwright`
const version = readdirSync(cache).filter(x => x.startsWith('chromium-')).sort().at(-1)
const browser = await chromium.launch({ executablePath: `${cache}/${version}/chrome-linux64/chrome`, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const out = '/tmp/pelagos-v05-extra'
mkdirSync(out, { recursive: true })
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
page.setDefaultTimeout(20000)
const errors = []
page.on('pageerror', e => errors.push(e.message))
const nav = name => page.getByRole('navigation').getByRole('button', { name, exact: true })
const button = name => page.getByRole('button', { name, exact: true })
const shot = name => page.screenshot({ path: `${out}/${name}.png` })
try {
  await page.goto('http://localhost:4173/pelagos/')
  await page.waitForTimeout(11000)
  assert.equal(await button('船隊').getAttribute('aria-pressed'), 'true')
  await button('海況').click()
  assert.equal(await button('海況').getAttribute('aria-pressed'), 'true')
  await page.getByText('圖層資料期間', { exact: true }).click()
  await page.getByText(/洋流 \d{4}/).waitFor()
  await button('周邊活動').click()
  await page.getByText(/港口 \d{4}/).waitFor()
  await shot('activity')
  await page.mouse.click(853, 589)
  await button('關閉詳情').waitFor()
  await shot('activity-detail')
  await button('關閉詳情').click()
  await page.mouse.click(1014, 512)
  await page.getByRole('heading', { name: 'Majuro', exact: true }).waitFor()
  await shot('port-detail')
  await button('關閉詳情').click()
  console.log('OK 活動聚合與港口標記點擊詳情')
  await button('回放').click()
  await page.getByRole('slider', { name: '回放時間' }).focus()
  await page.keyboard.press('Home')
  await page.getByText('僅船隊／浮標回放，背景資料期間固定').waitFor()
  await button('關閉回放').click()
  console.log('OK 視角切換、真實期間、回放範圍')

  await nav('船舶管理').click()
  await page.getByRole('button', { name: /編輯.*104/ }).click()
  await page.getByLabel('船長', { exact: true }).fill('尚未儲存的測試草稿')
  await page.getByRole('button', { name: /編輯.*105/ }).click()
  await button('編輯 藍潮 104').click()
  assert.equal(await page.getByLabel('船長', { exact: true }).inputValue(), '尚未儲存的測試草稿')
  await nav('警示中心').click()
  const attention = page.getByRole('button', { name: /^需處理 \d+$/ })
  const count = Number((await attention.innerText()).match(/\d+/)[0])
  assert.equal(await button('標記已處理').count(), count)
  await page.getByRole('button', { name: /^一般通知 \d+$/ }).click()
  assert.ok(await button('標記已處理').count() > 0)
  await nav('船舶管理').click()
  assert.equal(await page.getByLabel('船長', { exact: true }).inputValue(), '尚未儲存的測試草稿')
  await button('捨棄草稿').click()
  console.log('OK 跨船、跨頁草稿保護與警示分類計數')

  await nav('資料串接').click()
  await button('NOAA 海況').click()
  await page.getByText('NOAA 海況管線', { exact: true }).waitFor()
  await shot('sources')
  await button('匯入檔案').click()
  await page.locator('input[type=file]').setInputFiles({ name: 'v05.csv', mimeType: 'text/csv', buffer: Buffer.from('lon,lat,name\n155,5,測試點') })
  await button('加入地圖').click()
  await page.getByText('v05.csv', { exact: true }).waitFor()
  await shot('import')
  console.log('OK 來源與匯入分頁、CSV 寫入')

  await page.setViewportSize({ width: 393, height: 852 })
  await nav('戰情總覽').click()
  await button('船隊').click()
  await button('收起').click()
  assert.equal(Math.round((await page.locator('[data-drawer]').boundingBox()).height), 42)
  await shot('mobile-collapsed')
  await button('詳情').click()
  assert.ok((await page.locator('[data-drawer]').boundingBox()).height > 500)
  await button('摘要').click()
  await shot('mobile-summary')
  await button('更多模組').click()
  await nav('資料串接').filter({ visible: true }).click()
  await page.getByRole('heading', { name: '資料串接', exact: true }).waitFor()
  await shot('mobile-data')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await button('更多模組').click()
  await nav('FAD 浮標').filter({ visible: true }).click()
  await page.getByRole('heading', { name: 'FAD 浮標', exact: true }).waitFor()
  console.log('OK 手機三段抽屜、更多入口、無水平溢出')

  const failure = await browser.newPage()
  await failure.route('**/data/ocean.json', route => route.fulfill({ status: 503, body: 'test' }))
  await failure.goto('http://localhost:4173/pelagos/')
  await failure.getByRole('button', { name: '重試海況資料' }).waitFor()
  await failure.unroute('**/data/ocean.json')
  await failure.getByRole('button', { name: '重試海況資料' }).click()
  await failure.waitForTimeout(11000)
  assert.equal(await failure.getByRole('button', { name: '重試海況資料' }).count(), 0)
  await failure.close()
  const optional = await browser.newPage()
  await optional.route('**/data/ports.json', route => route.fulfill({ status: 503, body: 'test' }))
  await optional.goto('http://localhost:4173/pelagos/')
  await optional.waitForTimeout(11000)
  await optional.getByRole('button', { name: '重試 港口' }).waitFor()
  await optional.unroute('**/data/ports.json')
  await optional.getByRole('button', { name: '重試 港口' }).click()
  await optional.getByRole('button', { name: '重試 港口' }).waitFor({ state: 'detached' })
  await optional.close()
  console.log('OK 必要／選用資料載入失敗可重試')
  assert.deepEqual(errors, [])
  console.log('V05 checks passed', out)
} catch (e) { await shot('failure'); throw e }
finally { await browser.close() }
